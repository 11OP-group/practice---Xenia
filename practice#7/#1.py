rating = int(input("Введите рейтинг товара "))

match rating:
    case 10|9:
        print(f'рейтинг {rating} - Отличный продукт!🥕 Рекомендую ')
    case 8|7:
        print(f'рейтинг {rating} - Хороший продукт!💋 Можно попробовать')
    case 6|5|4:
        print(f'рейтинг {rating} - Средний продукт!🧻 Пробуй на страх и риск')
    case 3|2|1:
        print(f'рейтинг {rating} - Плохой продукт!🚨 Не рекомендую!!!!')
